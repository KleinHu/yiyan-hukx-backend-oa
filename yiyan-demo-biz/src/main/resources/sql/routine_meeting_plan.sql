CREATE TABLE ROUTINE_MEETING_PLAN
(
    ID                BIGINT       NOT NULL,
    NAME              VARCHAR(180),
    GOAL              VARCHAR(300),
    LEADER_ID         VARCHAR(64),
    LEADER_NAME       VARCHAR(64),
    CREATOR_ID        VARCHAR(64),
    CREATOR_NAME      VARCHAR(64),
    START_DATE        DATE,
    END_DATE          DATE,
    ORIGINAL_END_DATE DATE,
    ISSUED_AT         DATE,
    PROGRESS          INT          DEFAULT 0,
    COMPLETED_AT      TIMESTAMP,
    DRAFT             INT          DEFAULT 1,
    CREATOR           VARCHAR(64),
    CREATE_TIME       TIMESTAMP,
    UPDATER           VARCHAR(64),
    UPDATE_TIME       TIMESTAMP,
    UPDATE_IP         VARCHAR(64),
    PRIMARY KEY (ID)
);

CREATE TABLE ROUTINE_MEETING_PLAN_WEEK
(
    ID                BIGINT       NOT NULL,
    PLAN_ID           BIGINT       NOT NULL,
    WEEK_START        DATE         NOT NULL,
    WEEK_END          DATE         NOT NULL,
    LEADER_ID         VARCHAR(64),
    LEADER_NAME       VARCHAR(64),
    PROGRESS          INT          DEFAULT 0,
    CONTENT           VARCHAR(1000),
    FIRST_FEEDBACK_AT TIMESTAMP,
    CREATOR           VARCHAR(64),
    CREATE_TIME       TIMESTAMP,
    UPDATER           VARCHAR(64),
    UPDATE_TIME       TIMESTAMP,
    UPDATE_IP         VARCHAR(64),
    PRIMARY KEY (ID)
);

CREATE UNIQUE INDEX UK_ROUTINE_PLAN_WEEK ON ROUTINE_MEETING_PLAN_WEEK (PLAN_ID, WEEK_START);
CREATE INDEX IDX_ROUTINE_PLAN_WEEK_PLAN ON ROUTINE_MEETING_PLAN_WEEK (PLAN_ID);
CREATE INDEX IDX_ROUTINE_PLAN_LEADER ON ROUTINE_MEETING_PLAN (LEADER_ID);
CREATE INDEX IDX_ROUTINE_PLAN_CREATOR ON ROUTINE_MEETING_PLAN (CREATOR_ID);
